"""
Seller / Inventory Screen  [F3]
================================
Flow A — Seller (Automatic Waste Generation):
  1. Company registers its primary product
  2. "Run AI Scan" → Gemini predicts probable industrial byproducts
  3. Each predicted byproduct is filtered through the Hazard Checker
  4. Non-hazardous items are auto-listed as pending → approved in inventory
  5. Hazardous items are quarantined (status=blocked) with reason shown

The screen also lets users:
  - Manually add custom product/byproduct listings
  - View all their listings with status pills
  - Delete their own listings
"""

